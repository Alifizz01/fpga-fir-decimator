"""Single source of truth for the register map.

python regmap.py  -> writes rtl/regmap_pkg.vhd and docs/regmap.md
"""
from pathlib import Path

VERSION = 0x0001_0000

# name, offset, access, reset, description
REGS = [
    ("CTRL", 0x00, "RW", 0x0, "bit0 ENABLE (1 = accept input samples). bit1 SOFT_RESET (write 1, self-clearing): clears sample history, decimation phase, output, SAMPLE_COUNT and OVERFLOW. Coefficients are kept."),
    ("DECIM", 0x04, "RW", 0x2, "bits[3:0] decimation factor R. Valid 2..8. Writes outside 2..8 are ignored (old value kept). Change only while ENABLE = 0, then pulse SOFT_RESET."),
    ("COEF_ADDR", 0x08, "RW", 0x0, "bits[4:0] tap index 0..31 used by COEF_DATA. Auto-increments (wraps 31 -> 0) after every COEF_DATA write."),
    ("COEF_DATA", 0x0C, "RW", 0x0, "bits[15:0] signed Q1.15 coefficient. Write stores h[COEF_ADDR]; read returns h[COEF_ADDR] sign-extended. All taps reset to 0."),
    ("STATUS", 0x10, "RW1C", 0x0, "bit0 OVERFLOW (sticky, set when an output saturated; write 1 to clear). bit1 BUSY (read-only, MAC running or output waiting for tready)."),
    ("SAMPLE_COUNT", 0x14, "RO", 0x0, "Number of output samples accepted by the downstream sink (wraps at 2^32)."),
    ("VERSION", 0x18, "RO", VERSION, "IP version, 0xMMMMmmmm (major.minor)."),
]


def vhdl() -> str:
    lines = [
        "-- GENERATED by regmap.py. Do not edit by hand.",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        "package regmap_pkg is",
    ]
    for name, off, _, reset, _ in REGS:
        lines.append(f"  constant ADDR_{name:<13}: natural := 16#{off:02X}#;")
    for name, _, _, reset, _ in REGS:
        lines.append(f"  constant RST_{name:<14}: std_logic_vector(31 downto 0) := x\"{reset:08X}\";")
    lines += ["end package;", ""]
    return "\n".join(lines)


def markdown() -> str:
    out = [
        "<!-- GENERATED by regmap.py. Do not edit by hand. -->",
        "# Register map",
        "",
        "AXI4-Lite, 32-bit data, byte addresses. Any other address returns SLVERR (resp = 0b10) on read and write; reads return 0.",
        "",
        "| Offset | Name | Access | Reset | Description |",
        "|---|---|---|---|---|",
    ]
    for name, off, acc, reset, desc in REGS:
        out.append(f"| 0x{off:02X} | {name} | {acc} | 0x{reset:08X} | {desc} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    root = Path(__file__).parent
    (root / "rtl/regmap_pkg.vhd").write_text(vhdl(), newline="\n")
    (root / "docs/regmap.md").write_text(markdown(), newline="\n")
